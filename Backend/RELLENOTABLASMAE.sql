INSERT INTO Matricula (EstudianteID, SeccionID, Fecha, Anio)
SELECT 
    E.EstudianteID,
    S.SeccionID,
    GETDATE(),
    2026
FROM Estudiante E
JOIN Grado G ON G.NombreGrado = 
CASE 
    -- PREBASICA
    WHEN YEAR(E.FechaNacimiento) = 2022 THEN 'PRE-KINDER'
    WHEN YEAR(E.FechaNacimiento) = 2021 THEN 'KINDER'
    WHEN YEAR(E.FechaNacimiento) = 2020 THEN 'PREPARATORIA'

    -- BASICA
    WHEN YEAR(E.FechaNacimiento) = 2019 THEN 'PRIMERO'
    WHEN YEAR(E.FechaNacimiento) = 2018 THEN 'SEGUNDO'
    WHEN YEAR(E.FechaNacimiento) = 2017 THEN 'TERCERO'
    WHEN YEAR(E.FechaNacimiento) = 2016 THEN 'CUARTO'
    WHEN YEAR(E.FechaNacimiento) = 2015 THEN 'QUINTO'
    WHEN YEAR(E.FechaNacimiento) = 2014 THEN 'SEXTO'

    -- MEDIA
    WHEN YEAR(E.FechaNacimiento) = 2013 THEN 'SEPTIMO'
    WHEN YEAR(E.FechaNacimiento) = 2012 THEN 'OCTAVO'
    WHEN YEAR(E.FechaNacimiento) = 2011 THEN 'NOVENO'
    WHEN YEAR(E.FechaNacimiento) = 2009 THEN 'DECIMO'
    WHEN YEAR(E.FechaNacimiento) = 2008 THEN 'UNDECIMO'
END
JOIN Seccion S 
    ON S.GradoID = G.GradoID 
   AND S.Letra = 'A'
   AND S.Anio = 2026
WHERE E.EstudianteID BETWEEN 15 AND 82;







